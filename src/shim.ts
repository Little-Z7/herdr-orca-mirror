import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { shQuote } from "./run.ts";

const MARKER = "# orca-mirror shim";

export function renderShim(nodeBin: string, mainPath: string): string {
  return `#!/bin/sh\n${MARKER} (generated by \`orca-mirror install-shim\`; rerun it if the plugin moves)\nexec ${shQuote(nodeBin)} --disable-warning=ExperimentalWarning ${shQuote(mainPath)} "$@"\n`;
}

export function renderCmdShim(nodeBin: string, mainPath: string): string {
  return `@echo off\r\nREM ${MARKER} (generated by orca-mirror install-shim)\r\n"${nodeBin}" --disable-warning=ExperimentalWarning "${mainPath}" %*\r\n`;
}

/** Install `~/.local/bin/orca-mirror` (and `.cmd` on Windows). Never overwrites a file this plugin did not write. */
export function installShim(opts: { home: string; nodeBin: string; mainPath: string; pathEnv: string }): { path: string; message: string; ok: boolean } {
  const path = join(opts.home, ".local/bin/orca-mirror");
  if (existsSync(path) && !readFileSync(path, "utf8").includes(MARKER)) {
    return { path, ok: false, message: `${path} exists and was not written by orca-mirror; leaving it alone` };
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, renderShim(opts.nodeBin, opts.mainPath));
  chmodSync(path, 0o755);
  if (process.platform === "win32" || opts.nodeBin.toLowerCase().endsWith(".exe")) {
    const cmdPath = `${path}.cmd`;
    if (!existsSync(cmdPath) || readFileSync(cmdPath, "utf8").includes(MARKER)) {
      writeFileSync(cmdPath, renderCmdShim(opts.nodeBin, opts.mainPath));
    }
  }
  const norm = (p: string) => p.replace(/[\\/]+$/, "").toLowerCase();
  const dir = dirname(path);
  const parts = opts.pathEnv.split(opts.pathEnv.includes(";") ? ";" : ":");
  const onPath = parts.includes(dir) || (process.platform === "win32" && parts.some((p) => norm(p) === norm(dir)));
  return { path, ok: true, message: `installed ${path}${onPath ? "" : ` (note: ${dir} is not on PATH)`}` };
}
